#!/usr/bin/env node
// Builds the client side search index for the PATINA documentation.
// Writes two files with the same content:
//   assets/search-index.json  the canonical artefact
//   assets/search-index.js    the same data as a global, so search works when a
//                             page is opened from disk, where fetch of a local
//                             file is blocked by the browser
// Node standard library only. Deterministic: same pages in, same bytes out.
// Run: node docs/tools/build-search-index.mjs

import { readFile, writeFile, readdir } from 'node:fs/promises';
import { join, resolve, relative, sep } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(fileURLToPath(new URL('..', import.meta.url)));

/*
 * Every page is indexed in full. An index that quietly stops partway through a
 * page is worse than a small one, because a search that finds nothing reads as
 * proof the word is not there. The size is reported on every run and the build
 * fails past the ceiling, so growth stays a decision somebody makes rather than
 * something that happens to them.
 */
const MAX_INDEX_BYTES = 512 * 1024;

async function loadNav() {
  const src = await readFile(join(ROOT, 'assets', 'nav-data.js'), 'utf8');
  const fake = {};
  new Function('window', src)(fake);
  if (!Array.isArray(fake.PATINA_NAV)) throw new Error('nav-data.js did not define window.PATINA_NAV');
  return fake.PATINA_NAV;
}

async function walk(dir) {
  const out = [];
  for (const entry of await readdir(dir, { withFileTypes: true })) {
    const full = join(dir, entry.name);
    if (entry.isDirectory()) {
      if (entry.name === 'tools' || entry.name === 'assets') continue;
      out.push(...(await walk(full)));
    } else if (entry.name.endsWith('.html')) {
      out.push(full);
    }
  }
  return out;
}

function strip(html) {
  return html
    .replace(/<script[\s\S]*?<\/script>/gi, ' ')
    .replace(/<style[\s\S]*?<\/style>/gi, ' ')
    .replace(/<svg[\s\S]*?<\/svg>/gi, ' ')
    .replace(/<[^>]+>/g, ' ')
    .replace(/&lt;/g, '<')
    .replace(/&gt;/g, '>')
    .replace(/&amp;/g, '&')
    .replace(/&quot;/g, '"')
    .replace(/&#39;/g, "'")
    .replace(/&nbsp;/g, ' ')
    .replace(/\s+/g, ' ')
    .trim();
}

function pick(html, re) {
  const m = html.match(re);
  return m ? m[1].trim() : '';
}

function headings(article) {
  const out = [];
  const re = /<h([23])[^>]*>([\s\S]*?)<\/h\1>/gi;
  let m;
  while ((m = re.exec(article))) {
    const text = strip(m[2]);
    if (text) out.push(text);
  }
  return out;
}

const nav = await loadNav();
const sectionOf = new Map();
const orderOf = new Map();
let order = 0;
for (const section of nav) {
  for (const page of section.pages) {
    sectionOf.set(page.path, section.title);
    orderOf.set(page.path, order++);
  }
}

const files = (await walk(ROOT)).sort();
const pages = [];
const problems = [];

for (const file of files) {
  const rel = relative(ROOT, file).split(sep).join('/');
  const html = await readFile(file, 'utf8');
  const article = pick(html, /<article[^>]*>([\s\S]*?)<\/article>/i);
  if (!article) { problems.push(`${rel}: no <article> element`); continue; }

  const declared = pick(html, /<body[^>]*data-page="([^"]+)"/i);
  if (declared !== rel) problems.push(`${rel}: data-page says "${declared}"`);
  if (!sectionOf.has(rel)) problems.push(`${rel}: not listed in assets/nav-data.js`);

  const title = pick(html, /<h1[^>]*>([\s\S]*?)<\/h1>/i);
  const text = strip(article);

  pages.push({
    p: rel,
    s: sectionOf.get(rel) || '',
    t: strip(title),
    h: headings(article),
    x: text,
    n: text.length,
  });
}

pages.sort((a, b) => (orderOf.get(a.p) ?? 1e9) - (orderOf.get(b.p) ?? 1e9));

for (const [path] of sectionOf) {
  if (!pages.some((p) => p.p === path)) problems.push(`${path}: listed in nav-data.js but no such file`);
}

const payload = { generator: 'docs/tools/build-search-index.mjs', pages };
const json = JSON.stringify(payload, null, 2) + '\n';
await writeFile(join(ROOT, 'assets', 'search-index.json'), json, 'utf8');
await writeFile(
  join(ROOT, 'assets', 'search-index.js'),
  '/* Generated by docs/tools/build-search-index.mjs. Do not edit by hand.\n' +
  '   Same content as search-index.json, exposed as a global so that search\n' +
  '   works when a page is opened straight from disk. */\n' +
  'window.PATINA_SEARCH = ' + JSON.stringify(payload) + ';\n',
  'utf8'
);

const words = pages.reduce((sum, p) => sum + p.x.split(' ').length, 0);
const truncated = pages.filter((p) => p.x.length < p.n);
console.log(`indexed ${pages.length} pages, ${words} words, every page in full`);
console.log(`pages truncated ${truncated.length}`);
console.log(`wrote assets/search-index.json (${json.length} bytes of ${MAX_INDEX_BYTES})`);
console.log('wrote assets/search-index.js');

if (json.length > MAX_INDEX_BYTES) {
  problems.push(
    `the index is ${json.length} bytes, past the ${MAX_INDEX_BYTES} byte ceiling. ` +
    'Either raise the ceiling on purpose or stop indexing something on purpose.'
  );
}

if (problems.length) {
  console.error('\nproblems:');
  for (const p of problems) console.error('  ' + p);
  process.exit(1);
}
